"""Convert fixed-size PNG frames to const, high-byte-first RGB565 C arrays.

Usage: python tools/convert_animation.py assets/space_cat
Requires Pillow. Generated arrays remain in STM32 Flash, not SRAM.
"""

from pathlib import Path
import argparse

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
WIDTH = HEIGHT = 96
FRAME_COUNT = 16
BACKGROUND = (8, 16, 32)


def rgb565_bytes(image):
    result = bytearray()
    for red, green, blue in image.convert("RGB").getdata():
        color = ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)
        result.extend((color >> 8, color & 0xFF))
    return bytes(result)


def rgb565_image(data, size):
    """Render the exact colors that will be sent to the LCD."""
    result = bytearray()
    for offset in range(0, len(data), 2):
        color = (data[offset] << 8) | data[offset + 1]
        red, green, blue = color >> 11, (color >> 5) & 63, color & 31
        result.extend(((red << 3) | (red >> 2),
                       (green << 2) | (green >> 4),
                       (blue << 3) | (blue >> 2)))
    return Image.frombytes("RGB", size, bytes(result))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("frames", type=Path)
    args = parser.parse_args()
    paths = sorted(args.frames.glob("frame_*.png"))
    if len(paths) != FRAME_COUNT:
        raise SystemExit(f"Expected {FRAME_COUNT} frame_XX.png files, got {len(paths)}")

    frames = []
    for path in paths:
        with Image.open(path) as image:
            if image.size != (WIDTH, HEIGHT):
                raise SystemExit(f"{path}: expected {WIDTH}x{HEIGHT}, got {image.size}")
            image = image.convert("RGBA")
            background = Image.new("RGBA", image.size, BACKGROUND + (255,))
            frames.append(rgb565_bytes(Image.alpha_composite(background, image)))

    header = f"""/* Generated by tools/convert_animation.py. Do not edit by hand. */
#ifndef SPACE_CAT_FRAMES_H
#define SPACE_CAT_FRAMES_H

#include <stdint.h>

#define SPACE_CAT_WIDTH {WIDTH}U
#define SPACE_CAT_HEIGHT {HEIGHT}U
#define SPACE_CAT_FRAME_COUNT {FRAME_COUNT}U
#define SPACE_CAT_FRAME_BYTES (SPACE_CAT_WIDTH * SPACE_CAT_HEIGHT * 2U)
#define SPACE_CAT_BACKGROUND 0x0884U

extern const uint8_t space_cat_frames[SPACE_CAT_FRAME_COUNT][SPACE_CAT_FRAME_BYTES];

#endif
"""
    (ROOT / "lcd" / "space_cat_frames.h").write_text(header, encoding="ascii")

    source = ['/* Generated RGB565 pixels: row-major, high byte first. */',
              '#include "space_cat_frames.h"', '',
              'const uint8_t space_cat_frames[SPACE_CAT_FRAME_COUNT][SPACE_CAT_FRAME_BYTES] = {']
    for index, data in enumerate(frames):
        source.append(f"    /* Frame {index:02d} */")
        source.append("    {")
        for start in range(0, len(data), 24):
            source.append("        " + ",".join(f"0x{value:02X}" for value in data[start:start + 24]) + ",")
        source.append("    },")
    source.append("};\n")
    (ROOT / "lcd" / "space_cat_frames.c").write_text("\n".join(source), encoding="ascii")

    # Preview uses RGB565 quantization and nearest-neighbor enlargement, like the LCD.
    previews = [rgb565_image(data, (WIDTH, HEIGHT)).resize(
        (WIDTH * 2, HEIGHT * 2), Image.Resampling.NEAREST) for data in frames]
    previews[0].save(args.frames / "animation.gif", save_all=True,
                     append_images=previews[1:], duration=80, loop=0, optimize=False)
    sheet = Image.new("RGB", (WIDTH * 4, HEIGHT * 4), BACKGROUND)
    for index, data in enumerate(frames):
        sheet.paste(rgb565_image(data, (WIDTH, HEIGHT)),
                    ((index % 4) * WIDTH, (index // 4) * HEIGHT))
    sheet.save(args.frames / "contact_sheet.png")

    # Round-trip through the preview colors must preserve every RGB565 byte.
    for data in frames:
        assert len(data) == WIDTH * HEIGHT * 2
        assert rgb565_bytes(rgb565_image(data, (WIDTH, HEIGHT))) == data
    print(f"Converted {len(frames)} frames ({WIDTH}x{HEIGHT}); "
          f"Flash pixel data: {sum(map(len, frames)):,} bytes; RGB565 round-trip OK")


if __name__ == "__main__":
    main()
